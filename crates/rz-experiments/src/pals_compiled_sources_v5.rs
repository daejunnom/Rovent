pub fn compiled_source_inventory_v5() -> Result<CompiledSourceInventoryV5, ManifestError> {
    let mut inventory = BTreeMap::new();
    for (name, files) in SOURCE_COMPONENT_FILES_V5 {
        if inventory.contains_key(*name) {
            return Err(ManifestError::Integrity(
                "duplicate compiled component".into(),
            ));
        }
        let rows: Vec<_> = files
            .iter()
            .map(|(path, bytes)| {
                (
                    (*path).to_owned(),
                    bytes.len() as u64,
                    Sha256::digest(bytes).into(),
                )
            })
            .collect();
        source_component_digest_v5(&rows)?;
        inventory.insert((*name).to_owned(), rows);
    }
    Ok(inventory)
}

pub fn compiled_source_components_v5() -> Result<BTreeMap<String, String>, ManifestError> {
    compiled_source_inventory_v5()?
        .into_iter()
        .map(|(name, files)| Ok((name, hex(&source_component_digest_v5(&files)?))))
        .collect()
}

/// Every declared component must be embedded by this executable. Additional
/// registered components cannot silently bypass the actual producer check.
pub fn verify_compiled_source_components_v5(
    declared: &BTreeMap<String, String>,
) -> Result<(), ManifestError> {
    let compiled = compiled_source_components_v5()?;
    if declared.is_empty()
        || declared
            .iter()
            .any(|(name, pin)| compiled.get(name) != Some(pin))
    {
        return Err(ManifestError::Integrity(
            "V5 source registration differs from executable source bytes".into(),
        ));
    }
    Ok(())
}

fn hex(bytes: &[u8; 32]) -> String {
    let mut output = String::with_capacity(64);
    for byte in bytes {
        use std::fmt::Write;
        write!(&mut output, "{byte:02x}").expect("String write");
    }
    output
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn declared_pins_must_match_actual_embedded_inventory() {
        let mut declared = compiled_source_components_v5().unwrap();
        verify_compiled_source_components_v5(&declared).unwrap();
        declared.insert("rules".into(), "0".repeat(64));
        assert!(verify_compiled_source_components_v5(&declared).is_err());
        let mut declared = compiled_source_components_v5().unwrap();
        declared.insert("unregistered".into(), "a".repeat(64));
        assert!(verify_compiled_source_components_v5(&declared).is_err());
    }
    #[test]
    fn inventories_cover_required_components_and_unique_safe_paths() {
        let inventory = compiled_source_inventory_v5().unwrap();
        let catalog: serde_json::Value =
            serde_json::from_str(PALS_SOURCE_INVENTORY_V5_JSON).unwrap();
        let registered = catalog["components"].as_object().unwrap();
        assert_eq!(registered.len(), inventory.len());
        for (name, files) in &inventory {
            let paths: std::collections::BTreeSet<_> = registered[name]
                .as_array()
                .unwrap()
                .iter()
                .map(|p| p.as_str().unwrap())
                .collect();
            assert_eq!(paths, files.iter().map(|row| row.0.as_str()).collect());
        }
        for name in crate::PALS_V5_BASE_SOURCE_COMPONENTS
            .into_iter()
            .chain(crate::PALS_V5_NATIVE_SOURCE_COMPONENTS)
            .chain(crate::PALS_V5_COLLECTION_SOURCE_COMPONENTS)
            .chain(crate::PALS_V5_TRAINING_SOURCE_COMPONENTS)
            .chain(crate::PALS_V5_PAIR_SOURCE_COMPONENTS)
        {
            assert!(inventory.contains_key(name), "{name}");
        }
        for files in inventory.values() {
            assert!((1..=256).contains(&files.len()));
            assert_eq!(
                files
                    .iter()
                    .map(|row| &row.0)
                    .collect::<std::collections::BTreeSet<_>>()
                    .len(),
                files.len()
            );
        }
    }
}
