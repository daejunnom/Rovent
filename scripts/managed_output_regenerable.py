"""Optional reclamation for the CPU-only static packing graph.

Only the graph explicitly registered by its producing validation may be
removed.  Model exports, verification metadata, failed runs, and any GPU
inputs/outputs are retained.  Old output records acquire no new authority.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import stat
import time

from managed_storage import StorageError, checked, read_record_snapshot, write_record
from storage_guard import lifetime, owner_proven_dead, reboot_proves_dead

SCHEMA = "rovezero.cpu-static-packing-reclamation.v1"
RELATIVE = Path("device-packing/device_public_pack.onnx")
MAX_GRAPH = 2 * 1024 * 1024


def _append_journal(fd, value):
    payload = (json.dumps(value, sort_keys=True, separators=(",", ":")) + "\n").encode()
    if len(payload) > 8192:
        raise StorageError("bounded CPU graph retirement journal required")
    offset = 0
    while offset < len(payload):
        written = os.write(fd, payload[offset:])
        if written <= 0:
            raise StorageError("CPU graph retirement journal write failed")
        offset += written
    os.fsync(fd)


def _file_pin(path):
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        before = os.fstat(fd)
        if (not stat.S_ISREG(before.st_mode) or before.st_nlink != 1
                or not 1 <= before.st_size <= MAX_GRAPH):
            raise StorageError("bounded single-link CPU graph required")
        digest = hashlib.sha256()
        while True:
            chunk = os.read(fd, 65536)
            if not chunk:
                break
            digest.update(chunk)
        after = os.fstat(fd)
        stamp = lambda s: (s.st_dev, s.st_ino, s.st_size, s.st_mtime_ns, s.st_ctime_ns)
        if stamp(before) != stamp(after) or stamp(after) != stamp(path.lstat()):
            raise StorageError("CPU graph changed during observation")
        return {"bytes": before.st_size, "sha256": digest.hexdigest(),
                "identity": [before.st_dev, before.st_ino], "stamp": list(stamp(before))}
    finally:
        os.close(fd)


def register_cpu_static_packing_artifact(lease, pin):
    """Register only a graph just generated by the original CPU validator."""
    lease.guard.assert_held()
    if (lease.record is None or lease.record.get("state") != "active" or lease.deferred
            or lease._preservation_enabled
            or lease.quarantine_receipts is not None or lease.quarantine_transition_receipts is not None):
        raise StorageError("original CPU validator output lease required")
    if (type(pin) is not dict or set(pin) != {"bytes", "sha256"}
            or type(pin["bytes"]) is not int or not 1 <= pin["bytes"] <= MAX_GRAPH
            or type(pin["sha256"]) is not str or len(pin["sha256"]) != 64
            or any(c not in "0123456789abcdef" for c in pin["sha256"])):
        raise StorageError("exact graph pin required")
    path = checked(lease.output / RELATIVE)
    actual = _file_pin(path)
    if (actual["bytes"], actual["sha256"]) != (pin["bytes"], pin["sha256"]):
        raise StorageError("CPU graph registration pin differs")
    registration = lease.output / ".rovezero-cpu-static-packing-registration.json"
    if registration.exists():
        raise StorageError("CPU graph already registered")
    write_record(registration, {"schema": SCHEMA, "scope": "weight_free_static_cpu_no_provider",
                               "output_key": lease.key, "relative": RELATIVE.as_posix(), **actual})


def cleanup_registered_cpu_graphs(manager, catalog, *, seconds=2, own_lease=None):
    """Reclaim registered CPU graphs while retaining all receipt evidence.

    The original supervisor's verified tree closure plus this specific static
    CPU validator's receipt supplies the completion evidence.  This is not a
    general physical-GPU-completion assertion. Any uncertainty is skipped.
    """
    result = {"removed_files": 0, "removed_bytes": 0, "protected": 0,
              "warnings": [], "output_total_changed": False,
              "observation_limit": "current-visible-proc-namespace-only; census is not atomic with deletion"}
    until = time.monotonic() + seconds

    def tick():
        if time.monotonic() >= until:
            raise StorageError("CPU graph cleanup deadline reached")

    try:
        direct = (own_lease is not None and own_lease.guard.stream is None
                  and own_lease.record is not None and own_lease.record.get("state") == "retained"
                  and own_lease.record.get("tree_gone") is True and own_lease.outer is None)
        supervised = manager is not None and manager.finished is True
        if sys_platform() != "linux" or not (direct or supervised):
            raise StorageError("completed Linux supervisor required")
        from managed_outputs import _read, identity
        from storage_code_retirement import _process_census
        for entry in catalog.iterdir():
            tick()
            if not entry.name.endswith(".json"):
                continue
            try:
                row = _read(entry)
                output = checked(Path(row["output"]))
                expected_key = hashlib.sha256(os.path.normcase(str(output)).encode()).hexdigest()
                if row.get("key") != expected_key or entry.name != expected_key + ".json":
                    raise StorageError("CPU validator catalog key changed")
                registration = output / ".rovezero-cpu-static-packing-registration.json"
                if not registration.exists():
                    continue
                registration_snapshot = read_record_snapshot(registration, schema=SCHEMA)
                mark = registration_snapshot[0]
                previous_journal = output / ".rovezero-cpu-static-packing-retirement.jsonl"
                if previous_journal.exists():
                    # Completed and uncertain/partial retirement attempts both
                    # retain their own evidence; neither is retried implicitly.
                    continue
                own_direct = (direct and row == own_lease.record and output == own_lease.output
                              and row.get("outer_supervisor") is None)
                if (row.get("state") != "retained" or row.get("tree_gone") is not True
                        or (not own_direct and row.get("closure") != "original_outer_supervisor")
                        or row.get("status") != "success" or row.get("deferred")
                        or mark.get("output_key") != row.get("key")
                        or mark.get("scope") != "weight_free_static_cpu_no_provider"
                        or mark.get("relative") != RELATIVE.as_posix()):
                    result["protected"] += 1
                    continue
                if not own_direct:
                    outer = row.get("outer_supervisor")
                    if not supervised or not isinstance(outer, dict) or not isinstance(outer.get("owner"), dict):
                        raise StorageError("CPU validator supervisor binding missing")
                    owner = outer["owner"]
                    current_owner = (outer.get("root") == str(manager.root)
                                     and owner == manager._identity())
                    now = lifetime()
                    if not (current_owner or reboot_proves_dead(owner.get("lifetime"), now)
                            or owner_proven_dead(owner.get("pid"), owner.get("lifetime"), now)):
                        result["protected"] += 1
                        continue
                if (row.get("identity") != identity(output)
                        or _read(output / ".rovezero-output.json") != row):
                    raise StorageError("CPU validator output identity changed")
                receipt_path = checked(output / "validation.json")
                receipt_info = receipt_path.lstat()
                if (not stat.S_ISREG(receipt_info.st_mode) or receipt_info.st_nlink != 1
                        or receipt_info.st_size > 1024 * 1024):
                    raise StorageError("CPU validation receipt too large")
                receipt = json.loads(receipt_path.read_bytes())
                receipt_stamp = (receipt_info.st_dev, receipt_info.st_ino, receipt_info.st_size,
                                 receipt_info.st_mtime_ns, receipt_info.st_ctime_ns)
                reread = receipt_path.lstat()
                if receipt_stamp != (reread.st_dev, reread.st_ino, reread.st_size,
                                     reread.st_mtime_ns, reread.st_ctime_ns):
                    raise StorageError("CPU validation receipt changed while read")
                evidence = receipt.get("device_packing_static_interop", {})
                asset = evidence.get("assets", {}).get(RELATIVE.name)
                if (receipt.get("schema") != "rovezero.pals-cpu-model-validation.v1"
                        or receipt.get("status") != "success" or receipt.get("provider") != "cpu"
                        or receipt.get("gpu_validation") != "not_run"
                        or evidence.get("scope") != "python_artifact_rust_fixed_body_check_only"
                        or evidence.get("rust_body_exit_status") != 0
                        or asset != {"bytes": mark.get("bytes"), "sha256": mark.get("sha256")}):
                    raise StorageError("CPU static validation evidence missing")
                target = checked(output / RELATIVE)
                pin = _file_pin(target)
                if pin != {key: mark[key] for key in ("bytes", "sha256", "identity", "stamp")}:
                    raise StorageError("CPU static graph changed")
                parent_info = target.parent.lstat()
                parent_identity = (parent_info.st_dev, parent_info.st_ino)
                census = _process_census({tuple(pin["identity"]), tuple(row["identity"]), parent_identity}, set(), tick)
                if not isinstance(census, dict) or census.get("complete") is not True:
                    raise StorageError("CPU graph process census incomplete")
                tick()
                if _read(entry) != row or _read(output / ".rovezero-output.json") != row:
                    raise StorageError("CPU validator output changed during cleanup")
                if read_record_snapshot(registration, schema=SCHEMA) != registration_snapshot:
                    raise StorageError("CPU graph registration changed during cleanup")
                receipt_check = receipt_path.lstat()
                if receipt_stamp != (receipt_check.st_dev, receipt_check.st_ino, receipt_check.st_size,
                                     receipt_check.st_mtime_ns, receipt_check.st_ctime_ns):
                    raise StorageError("CPU validation receipt changed during cleanup")
                root_fd = os.open(output, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
                parent_fd = None
                journal_fd = None
                try:
                    root_info = os.fstat(root_fd)
                    if [root_info.st_dev, root_info.st_ino] != row["identity"]:
                        raise StorageError("CPU validator root changed")
                    parent_fd = os.open("device-packing", os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW,
                                        dir_fd=root_fd)
                    parent_info = os.fstat(parent_fd)
                    if (parent_info.st_dev, parent_info.st_ino) != parent_identity:
                        raise StorageError("CPU graph parent changed after process census")
                    named = os.stat(target.name, dir_fd=parent_fd, follow_symlinks=False)
                    stamp = [named.st_dev, named.st_ino, named.st_size,
                             named.st_mtime_ns, named.st_ctime_ns]
                    if stamp != pin["stamp"] or named.st_nlink != 1:
                        raise StorageError("CPU graph changed immediately before unlink")
                    record = {"schema": SCHEMA, "status": "unlink_pending",
                              "relative": RELATIVE.as_posix(), "pin": pin,
                              "physical_gpu_completion_attested": False}
                    journal_fd = os.open(".rovezero-cpu-static-packing-retirement.jsonl",
                                         os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW,
                                         0o600, dir_fd=root_fd)
                    _append_journal(journal_fd, record)
                    os.fsync(root_fd)
                    tick()
                    if (_read(entry) != row or _read(output / ".rovezero-output.json") != row
                            or read_record_snapshot(registration, schema=SCHEMA) != registration_snapshot):
                        raise StorageError("CPU validator output changed after journal")
                    receipt_check = receipt_path.lstat()
                    if receipt_stamp != (receipt_check.st_dev, receipt_check.st_ino, receipt_check.st_size,
                                         receipt_check.st_mtime_ns, receipt_check.st_ctime_ns):
                        raise StorageError("CPU validation receipt changed after journal")
                    named_parent = os.stat("device-packing", dir_fd=root_fd, follow_symlinks=False)
                    named = os.stat(target.name, dir_fd=parent_fd, follow_symlinks=False)
                    if ((named_parent.st_dev, named_parent.st_ino) != (parent_info.st_dev, parent_info.st_ino)
                            or [named.st_dev, named.st_ino, named.st_size,
                                named.st_mtime_ns, named.st_ctime_ns] != pin["stamp"]
                            or identity(output) != row["identity"]):
                        raise StorageError("CPU graph path changed after journal")
                    os.unlink(target.name, dir_fd=parent_fd)
                    os.fsync(parent_fd)
                    result["removed_files"] += 1
                    result["removed_bytes"] += pin["bytes"]
                    result["output_total_changed"] = True
                    _append_journal(journal_fd, {**record, "status": "unlinked"})
                finally:
                    if journal_fd is not None:
                        os.close(journal_fd)
                    if parent_fd is not None:
                        os.close(parent_fd)
                    os.close(root_fd)
            except (OSError, StorageError, ValueError, KeyError, TypeError) as error:
                result["protected"] += 1
                result["warnings"].append(f"{type(error).__name__}: {str(error)[:128]}")
    except (OSError, StorageError, RuntimeError) as error:
        result["warnings"].append(f"{type(error).__name__}: {str(error)[:128]}")
    return result


def sys_platform():
    import sys
    return sys.platform
